-- 2026-07-01에 인천이 2군8구 -> 2군9구로 재편됐다.
--   중구(내륙) + 동구 -> 제물포구
--   중구 영종도·용유·무의도 -> 영종구
--   서구 아라뱃길 남단 -> 서해구 (개칭)
--   서구 아라뱃길 북단 8개동 -> 검단구 (신설)
--
-- 그런데 20260923010000_fix_stale_district_names.sql이 검단구·서해구를 "존재하지 않는
-- 표기"로 보고 서구로 되돌렸다. 정반대였다. 동행복권(=당첨점 수집 경로)이 맞는 새 이름을
-- 보내오고 있었고, 우리는 2025-06 공공데이터 CSV의 옛 이름을 기준으로 삼아 그걸 덮었다.
--
-- 여기서는 **주소 글자에 새 구 이름이 이미 적혀 있는 행만** 바로잡는다. 주소가 아직
-- "서구/중구/동구"인 행은 손대지 않는다 - 그 행이 원래 어느 신설 구였는지 DB에 남아
-- 있지 않고(위 마이그레이션이 주소 글자까지 덮어썼다), 경계가 아라뱃길을 따라 갈라져서
-- 좌표로도 못 가른다. 추측해서 125곳에 틀린 구를 박는 것보다 옛 이름으로 두는 게 낫다.
-- 복구는 최신 판매점 주소 CSV를 다시 받아 재적재하는 쪽이다.
update public.stores
set sigungu = substring(address from '^인천광역시 ([^ ]+[시군구]) ')
where sido = '인천광역시'
  and address ~ '^인천광역시 (검단구|서해구|제물포구|영종구) '
  and sigungu <> substring(address from '^인천광역시 ([^ ]+[시군구]) ');

select public.refresh_store_ranking_stats();
